-- 1. SESSION RECORDINGS TABLE (CANONICAL METADATA)
CREATE TABLE IF NOT EXISTS public.session_recordings (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  event_id UUID REFERENCES public.events(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  storage_path TEXT,
  file_size_bytes BIGINT,
  duration_seconds INTEGER DEFAULT 2100,
  thumbnail_path TEXT,
  uploaded_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  uploaded_at TIMESTAMPTZ DEFAULT NOW(),
  status TEXT NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('NOT_AVAILABLE', 'PROCESSING', 'AVAILABLE', 'ERROR')),
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  duration TEXT NOT NULL DEFAULT '35 min',
  category TEXT NOT NULL DEFAULT 'El Presente',
  video_url TEXT,
  thumbnail_url TEXT,
  zoom_recording_url TEXT,
  recording_strategy TEXT NOT NULL DEFAULT 'HOSTED' CHECK (recording_strategy IN ('HOSTED', 'EXTERNAL')),
  external_url TEXT,
  views_count INTEGER DEFAULT 0,
  is_member_only BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_session_recordings_event ON public.session_recordings(event_id);
CREATE INDEX IF NOT EXISTS idx_session_recordings_date ON public.session_recordings(date DESC);
CREATE INDEX IF NOT EXISTS idx_session_recordings_status ON public.session_recordings(status);

