-- 3. STORAGE ROW LEVEL SECURITY POLICIES

-- Enable RLS on storage.objects
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;

-- 3.1 Profile Images: Publicly readable; Users can upload/update/delete only in their own folder
CREATE POLICY "Profile images are publicly viewable"
  ON storage.objects FOR SELECT
  USING (bucket_id = 'profile-images');

CREATE POLICY "Authenticated users can upload own profile image"
  ON storage.objects FOR INSERT
  WITH CHECK (
    bucket_id = 'profile-images' 
    AND auth.role() = 'authenticated'
  );

CREATE POLICY "Users can update own profile image"
  ON storage.objects FOR UPDATE
  USING (
    bucket_id = 'profile-images' 
    AND auth.uid()::text = (storage.foldername(name))[1]
  );

-- 3.2 Session Recordings: STRICTLY PRIVATE BUCKET
-- Direct public select is completely denied.
-- Only admins can directly read/write storage objects.
-- Members access files strictly via temporary signed URLs generated by backend.
CREATE POLICY "Admins have full access to session recordings storage"
  ON storage.objects FOR ALL
  USING (
    bucket_id = 'session-recordings'
    AND public.is_admin(auth.uid())
  );

-- 3.3 Book Covers & Content Media: Publicly readable; Admin writable
CREATE POLICY "Book covers are publicly viewable"
  ON storage.objects FOR SELECT
  USING (bucket_id = 'book-covers' OR bucket_id = 'content-media');

CREATE POLICY "Admins can manage book covers and media"
  ON storage.objects FOR ALL
  USING (
    (bucket_id = 'book-covers' OR bucket_id = 'content-media')
    AND public.is_admin(auth.uid())
  );

-- 3.4 Resources: Authenticated members can read; Admin can manage
CREATE POLICY "Members can view resources"
  ON storage.objects FOR SELECT
  USING (
    bucket_id = 'resources'
    AND auth.role() = 'authenticated'
  );

CREATE POLICY "Admins can manage resources files"
  ON storage.objects FOR ALL
  USING (
    bucket_id = 'resources'
    AND public.is_admin(auth.uid())
  );
